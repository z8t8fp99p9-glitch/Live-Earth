"""Command-line interface for LIVE // EARTH Global Collector."""
from __future__ import annotations

from pathlib import Path
import argparse
import json
import sys

from . import __version__
from .collector import GlobalCollector
from .errors import GlobalCollectorError


def _read_job(path: str) -> dict:
    try:
        raw = sys.stdin.read() if path == "-" else Path(path).read_text(encoding="utf-8")
        job = json.loads(raw)
    except Exception as exc:
        raise GlobalCollectorError(f"Could not read Manager job JSON: {exc}") from exc
    if not isinstance(job, dict):
        raise GlobalCollectorError("Manager job input must be a JSON object.")
    return job


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        prog="global-collector",
        description="One universal collector for all registered LIVE // EARTH Views and public source formats.",
    )
    parser.add_argument("--job-file", required=True,
                        help="JSON job generated by Global Collection Manager; use '-' for stdin.")
    parser.add_argument("--repository-root", default=".",
                        help="Repository root containing global_collection_manager/config/.")
    parser.add_argument("--version", action="version", version=f"Global Collector {__version__}")
    args = parser.parse_args(argv)
    try:
        job = _read_job(args.job_file)
        result = GlobalCollector(Path(args.repository_root)).collect(job)
        json.dump(result, sys.stdout, ensure_ascii=False, indent=2)
        sys.stdout.write("\n")
        return 0 if result["status"] in {"succeeded", "partial"} else 2
    except (GlobalCollectorError, OSError, ValueError, TypeError) as exc:
        error = {
            "collector": "LIVE // EARTH Global Collector",
            "collectorVersion": __version__,
            "status": "blocked",
            "collectorMakesRightsDecisions": False,
            "databaseWritesPerformed": False,
            "errorType": type(exc).__name__,
            "message": str(exc),
        }
        json.dump(error, sys.stderr, ensure_ascii=False, indent=2)
        sys.stderr.write("\n")
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
