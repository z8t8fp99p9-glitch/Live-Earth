"""Command-line interface for Global Collector."""
from __future__ import annotations

from pathlib import Path
import argparse
import json
import sys

from .collector import GlobalCollector
from .errors import GlobalCollectorError


def _read_job(path: str) -> dict:
    try:
        if path == "-":
            raw = sys.stdin.read()
        else:
            raw = Path(path).read_text(encoding="utf-8")
        job = json.loads(raw)
    except Exception as exc:
        raise GlobalCollectorError(f"Could not read Manager job JSON: {exc}") from exc
    if not isinstance(job, dict):
        raise GlobalCollectorError("Manager job input must be a JSON object.")
    return job


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        prog="global-collector",
        description="Fetches and normalizes approved View-specific feeds for Global Checker.",
    )
    parser.add_argument(
        "--job-file", required=True,
        help="JSON job generated by Global Collection Manager; use '-' to read from stdin.",
    )
    parser.add_argument(
        "--repository-root", default=".",
        help="LIVE // EARTH repository root containing both Manager and Checker registries.",
    )
    args = parser.parse_args(argv)

    try:
        job = _read_job(args.job_file)
        collector = GlobalCollector(Path(args.repository_root))
        result = collector.collect(job)
        json.dump(result, sys.stdout, ensure_ascii=False, indent=2)
        sys.stdout.write("\\n")
        return 0 if result["status"] in {"succeeded", "partial"} else 2
    except (GlobalCollectorError, OSError, ValueError, TypeError) as exc:
        error = {
            "collector": "LIVE // EARTH Global Collector",
            "status": "blocked",
            "databaseWritesPerformed": False,
            "errorType": type(exc).__name__,
            "message": str(exc),
        }
        json.dump(error, sys.stderr, ensure_ascii=False, indent=2)
        sys.stderr.write("\\n")
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
