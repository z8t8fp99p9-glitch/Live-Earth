const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '..', 'Weather/weather-view.js'), 'utf8');
assert.ok(source.includes('position:absolute!important; inset:0!important'));
assert.ok(source.includes('width:100%!important; height:100%!important'));
assert.ok(source.includes('viewBox="0 0 420 300"'));
assert.ok(source.includes('preserveAspectRatio="xMidYMax slice"'));
assert.ok(source.includes('.le-weather-landscape {'));
assert.ok(source.includes('height:58%'));
assert.ok(source.includes('@media (orientation:landscape) and (max-height:520px)'));
assert.ok(source.includes('data-phase="night"'));
assert.ok(source.includes('data-phase="dawn"'));
assert.ok(source.includes('data-phase="evening"'));
assert.ok(source.includes('data-weather="rain"'));
assert.ok(source.includes('data-weather="snow"'));
assert.ok(source.includes('data-weather="storm"'));
assert.ok(source.includes('prefers-reduced-motion:reduce'));
assert.ok(!source.includes('scaleX') && !source.includes('scaleZ'));
console.log('Original 2D composition, responsive crop, and weather/day-night atmosphere checks passed.');
