const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '..', 'Weather/weather-view.js'), 'utf8');

assert.ok(source.includes('viewBox="0 0 420 520"'), 'Portrait uses the ZIP landscape artwork in a full-width fit');
assert.ok(source.includes('viewBox="0 0 1600 900"'), 'Landscape has its own composition');
assert.ok(source.includes('preserveAspectRatio="xMidYMax slice"'), 'Portrait artwork keeps its proportions');
assert.ok(source.includes('preserveAspectRatio="xMidYMid slice"'), 'Wide artwork crops without stretching');
assert.ok(source.includes('@media (orientation:landscape)'));
assert.ok(source.includes('.le-weather-landscape-wide { display:block; }'));
assert.ok(source.includes('le-weather-sun'));
assert.ok(source.includes('le-weather-moon'));
assert.ok(source.includes('le-weather-stars'));
assert.ok(source.includes('le-weather-cloud-layer'));
assert.ok(source.includes('data-phase="night"'));
assert.ok(source.includes('data-phase="dawn"'));
assert.ok(source.includes('data-phase="evening"'));
assert.ok(source.includes('data-condition="rain"'));
assert.ok(source.includes('data-condition="snow"'));
assert.ok(source.includes('data-condition="storm"'));
assert.ok(source.includes('prefers-reduced-motion:reduce'));
console.log('Portrait/landscape adaptation, soft sky palettes and weather atmosphere checks passed.');
