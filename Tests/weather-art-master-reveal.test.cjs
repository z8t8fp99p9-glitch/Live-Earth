'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const runtime = fs.readFileSync(path.join(root, 'Weather/Art/live-art-online.js'), 'utf8');
const catalogue = JSON.parse(fs.readFileSync(path.join(root, 'Weather/Art/art-library.json'), 'utf8'));
const score = JSON.parse(fs.readFileSync(path.join(root, 'Weather/Art/clear-valley-artist-001.json'), 'utf8'));
assert.doesNotMatch(runtime, /createMasterRevealRenderer|masterImagePath|stageMaskAtlasPath|fetchMasterImage|ordered-master-brush-reveal|drawImage\(masterImage/);
assert.equal(score.schemaVersion, 1);
assert.equal(score.renderMode, 'ordered-ink-wash-paths');
assert.equal(score.paths.length, 100);
const clear = catalogue.artworks.find(item => item.weather.includes('clear'));
assert.equal(clear.id, score.id);
assert.equal(clear.rendererVersion, 1);
assert.equal(clear.renderMode, 'ordered-ink-wash-paths');
assert.equal(clear.sourceImage, null);
assert.equal(clear.maskAtlas, null);
assert.equal(catalogue.productionStandard.masterImageReveal, false);
assert.equal(catalogue.productionStandard.stageMaskInput, false);
console.log('PASS: Clear routes through Rain schema-v1 paths; master-image reveal assets are not used.');
