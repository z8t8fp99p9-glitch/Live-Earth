const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '..', 'Weather/weather-view.js'), 'utf8');
const art = path.join(__dirname, '..', 'Weather/Assets/weather-scene.webp');
assert.ok(fs.existsSync(art));
assert.ok(source.includes("runtime.registerFeature('weather', activateWeather)"));
assert.ok(source.includes("const view = mount('weather')"));
assert.ok(source.includes('function createArt()'));
assert.ok(source.includes('api.open-meteo.com/v1/forecast'));
for (const field of ['temperature_2m','apparent_temperature','relative_humidity_2m','weather_code','wind_speed_10m','precipitation_probability','temperature_2m_max','temperature_2m_min','pressure_msl','visibility','uv_index']) assert.ok(source.includes(field), `Missing weather field ${field}`);
for (const token of ['le-weather-art-image','le-weather-art-wash','le-weather-art-light','le-weather-rain','le-weather-snow','le-weather-fog','le-weather-lightning','le-weather-headline','le-weather-hourly','le-weather-dew-drops','le-weather-ripples']) assert.ok(source.includes(token));
assert.ok(source.includes('live-earth-location-state'));
assert.ok(source.includes('live-earth-location-stop'));
assert.ok(source.includes("window.addEventListener('offline'"));
assert.ok(source.includes("window.addEventListener('online'"));
assert.ok(source.includes('prefers-reduced-motion:reduce'));
for (const forbidden of ['navigator.geolocation','getCurrentPosition(','watchPosition(','WebGLRenderer','new THREE.','Living Topography']) assert.ok(!source.includes(forbidden), `Weather production view must not use ${forbidden}`);
console.log('Photographic 2D artwork, current/hourly/daily data, weather-reactive layers and no-3D/no-GPS checks passed.');
