const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '..', 'Weather/weather-view.js'), 'utf8');
const art = path.join(__dirname, '..', 'Weather/Assets/weather-scene.webp');
assert.ok(fs.existsSync(art), 'The photographic weather scene must ship with the Weather view');
assert.ok(source.includes('src="./Weather/Assets/weather-scene.webp"'));
assert.ok(source.includes('le-weather-art-image'));
assert.ok(source.includes('le-weather-maple') === false, 'The production scene must not use the former primitive SVG maple artwork');
assert.ok(source.includes('le-weather-art-mark'));
assert.ok(source.includes('le-weather-pagoda') === false, 'The production scene must use photographic art, not geometric pagoda shapes');
assert.ok(source.includes('le-weather-dew-drops'));
assert.ok(source.includes('le-weather-ripples'));
assert.ok(source.includes('le-weather-leaf-motion'));
assert.ok(source.includes('prefers-reduced-motion:reduce'));
assert.doesNotMatch(source, /characterMarkup|le-weather-person|le-weather-people|le-weather-ball|日本語/);
console.log('Photographic Japanese-inspired artwork, restrained ink-art accent and live natural effects checks passed.');
